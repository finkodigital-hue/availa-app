import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import { PGlite } from '@electric-sql/pglite';
const exported = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/booking-attribution.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, {exports:exported, URLSearchParams});
assert.equal(exported.bookingSourceFromSearch('?utm_source=google&email=private'), 'google');
assert.equal(exported.bookingSourceFromSearch('?utm_source=instagram'), 'instagram');
assert.equal(exported.bookingSourceFromSearch('?utm_source=somewhere-else'), null);
assert.equal(exported.bookingSourceFromSearch(''), null);
assert.equal(exported.normalizeBookingSource({source:'google'}), null);
const db = new PGlite();
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema auth;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
create table businesses(id uuid primary key,owner_id uuid);
create table bookings(id uuid primary key,business_id uuid,created_at timestamptz default now(),status text);
insert into businesses values('${id(1)}','${id(10)}'),('${id(2)}','${id(20)}');
insert into bookings(id,business_id,status) values('${id(3)}','${id(1)}','confirmed'),('${id(4)}','${id(1)}','completed'),('${id(5)}','${id(1)}','pending'),('${id(6)}','${id(2)}','confirmed');`);
await db.exec(fs.readFileSync('supabase/migrations/20260924006000_booking_source_reporting.sql','utf8'));
await db.exec(`select record_booking_source('${id(3)}','${id(1)}','google'); select record_booking_source('${id(3)}','${id(1)}','instagram');`);
assert.equal((await db.query('select count(*)::int as n from booking_sources')).rows[0].n,1,'Retry does not double count');
await assert.rejects(db.exec(`select record_booking_source('${id(3)}','${id(2)}','google')`),/workspace mismatch/);
await assert.rejects(db.exec(`select record_booking_source('${id(4)}','${id(1)}','evil')`),/Invalid booking source/);
await db.exec(`set test.uid='${id(10)}'`);
const rows = (await db.query(`select * from booking_source_report('${id(1)}')`)).rows;
assert.equal(Number(rows.find(r=>r.source==='google').booking_count),1);
assert.equal(Number(rows.find(r=>r.source==='unattributed').booking_count),1);
assert.equal(rows.length,2,'Pending excluded');
await assert.rejects(db.exec(`select * from booking_source_report('${id(2)}')`),/Only the business owner/);
await db.exec('set role authenticated');
await assert.rejects(db.exec(`select record_booking_source('${id(4)}','${id(1)}','google')`),/permission denied/);
await assert.rejects(db.exec('select * from booking_sources'),/permission denied/);
await db.exec('reset role');
await db.exec(`update bookings set status='cancelled' where id='${id(3)}'`);
assert.equal((await db.query(`select * from booking_source_report('${id(1)}')`)).rows.length,1,'Cancelled excluded');
await db.close();
console.log('Booking attribution: allowlist, idempotency, owner isolation, grants and status filters passed (fictional database only)');
