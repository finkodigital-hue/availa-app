import assert from 'node:assert/strict';
export async function checkSchemaPaymentLedger(db) {
 const id=n=>`10000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 let checks=0;const same=(a,b,label)=>{assert.deepEqual(a,b,label);checks++;};
 const query=async(sql,args=[])=>(await db.query(sql,args)).rows;
 const fail=async(sql,args,pattern)=>{await assert.rejects(db.query(sql,args),pattern);checks++;};
 await db.exec('reset role');
 await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({role:'service_role'})]);
 await db.exec(`update businesses set currency='GBP' where id='${id(101)}';
  update bookings set price_cents=1000,amount_paid_cents=0,amount_due_cents=1000,payment_status='unpaid' where id in('${id(501)}','${id(503)}');`);
 const issue=async(hash,currency='gbp',key='issue:'+hash)=>(await query('select issue_gift_card($1,1500,$2,$3,\'TEST\',\'Fictional\',\'\',\'\',$4,$5) as id',[id(101),currency,hash,id(1),key]))[0].id;
 const a='a'.repeat(64),b='b'.repeat(64);
 const card=await issue(a);
 const redeem=async(booking=id(501),hash=a,key='redeem:first')=>(await query('select * from redeem_gift_card($1,$2,$3,$4,$5)',[id(101),booking,hash,id(1),key]))[0];
 const first=await redeem();same(first.amount_cents,1000,'Gift pays due amount');same(first.balance_cents,500,'Gift retains remainder');
 same((await query(`select amount_due_cents from bookings where id='${id(501)}'`))[0].amount_due_cents,0,'Gift updates amount due');
 same(await redeem(),first,'Identical redemption replay');
 await assert.rejects(redeem(id(503),a),/identity|mismatch/i);checks++;
 await assert.rejects(redeem(id(501),b),/identity|mismatch/i);checks++;
 await issue(b,'usd');await assert.rejects(redeem(id(503),b,'redeem:currency'),/currency/i);checks++;
 await db.query('update gift_cards set expires_at=now()-interval \'1 second\' where id=$1',[card]);
 await assert.rejects(redeem(id(503),a,'redeem:expired'),/expired/i);checks++;
 await db.query('update gift_cards set expires_at=null where id=$1',[card]);
 await db.exec(`update bookings set amount_refunded_cents=1 where id='${id(503)}'`);
 await assert.rejects(redeem(id(503),a,'redeem:refunded'),/review/i);checks++;
 await db.exec(`update bookings set amount_refunded_cents=0 where id='${id(503)}';
  update businesses set stripe_account_id='acct_fictional',stripe_charges_enabled=true where id='${id(101)}';
  select claim_balance_checkout('${id(101)}','${id(503)}','https://example.invalid');`);
 await assert.rejects(redeem(id(503),a,'redeem:open-checkout'),/checkout|review/i);checks++;
 await db.exec(`delete from balance_checkout_attempts where booking_id='${id(503)}'`);
 same((await redeem(id(503),a,'redeem:remaining')).amount_cents,500,'Partial gift payment');
 same((await query(`select amount_due_cents from bookings where id='${id(503)}'`))[0].amount_due_cents,500,'Partial gift balance remains due');
 await db.exec(`update bookings set price_cents=5000,amount_paid_cents=5000,amount_due_cents=0,payment_status='paid',amount_refunded_cents=0 where id='${id(501)}';
  insert into payments(business_id,booking_id,type,status,amount_cents,currency,stripe_payment_intent_id) values('${id(101)}','${id(501)}','charge','succeeded',5000,'gbp','pi_schema_refund');`);
 const refund=(amount,key='re_schema_one',currency='gbp',booking=id(501))=>query('select fulfill_stripe_refund($1,$2,$3,$4,$5,$6,$7)',[id(101),booking,amount,currency,key,'pi_schema_refund',id(1)]);
 await refund(1000);checks++;
 same((await query(`select amount_refunded_cents,payment_status from bookings where id='${id(501)}'`))[0],{amount_refunded_cents:1000,payment_status:'partially_refunded'},'Partial refund recorded');
 await refund(1000);same((await query("select count(*)::int as n from payments where stripe_refund_id='re_schema_one'"))[0].n,1,'Refund replay single ledger entry');
 await assert.rejects(refund(1001),/identity|mismatch/i);checks++;
 await assert.rejects(refund(1000,'re_schema_one','usd'),/identity|mismatch|currency/i);checks++;
 await assert.rejects(refund(1000,'re_schema_one','gbp',id(503)),/identity|mismatch/i);checks++;
 await assert.rejects(refund(4001,'re_schema_over'),/amount/i);checks++;
 await assert.rejects(refund(-1,'re_schema_negative'),/Invalid/i);checks++;
 await assert.rejects(refund(null,'re_schema_null'),/Invalid/i);checks++;
 await refund(4000,'re_schema_two');checks++;
 same((await query(`select amount_refunded_cents,payment_status from bookings where id='${id(501)}'`))[0],{amount_refunded_cents:5000,payment_status:'refunded'},'Cumulative full refund');
 await db.exec('set role authenticated');
 await fail('select redeem_gift_card($1,$2,$3,$4,$5)',[id(101),id(501),a,id(1),'denied'],/permission denied/);
 await fail('select fulfill_stripe_refund($1,$2,1,\'gbp\',\'re_denied\',\'pi_schema_refund\',$3)',[id(101),id(501),id(1)],/permission denied/);
 await db.exec('reset role');
 console.log(`${checks} complete-schema gift redemption and refund-ledger assertions passed (fictional value; no provider calls).`);
}
